// Embeds app/kantor-3d.html into hooks/page.ts, so the mod can write the 3D page next to the roster.
// Also copies it to docs/index.html, the web app served by GitHub Pages (iPhone Home Screen, Mac Dock).
// Run after editing the page: node scripts/build-page.mjs
import { readFileSync, writeFileSync } from 'node:fs'
const root = new URL('..', import.meta.url).pathname
const { version } = JSON.parse(readFileSync(root + '.claude-plugin/plugin.json', 'utf8'))
const html = readFileSync(root + 'app/kantor-3d.html', 'utf8').replaceAll('__VERSION__', version)
writeFileSync(root + 'hooks/page.ts', '// Generated by scripts/build-page.mjs from app/kantor-3d.html. Do not edit by hand.\nexport const PAGE: string = ' + JSON.stringify(html) + '\n')
writeFileSync(root + 'docs/index.html', html)
console.log('hooks/page.ts', html.length, 'chars')
